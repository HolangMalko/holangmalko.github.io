function getInitialLanguage() {
    const saved = localStorage.getItem('app_lang');
    if (saved && translations[saved]) {
        return saved;
    }
    const navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (navLang.startsWith('ja')) {
        return 'ja';
    } else if (navLang.startsWith('en')) {
        return 'en';
    }
    return 'ko';
}

let currentLang = getInitialLanguage();

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('app_lang', lang);

    // Update active class on all language buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    // Update text elements with data-i18n
    const dict = translations[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (dict && dict[key]) {
            el.textContent = dict[key];
        }
    });

    // Toggle language blocks (for Policy, Terms, Guide pages with #policy-ko, #policy-en, etc.)
    document.querySelectorAll('.policy-lang-block, .terms-lang-block, .guide-lang-block, [id$="-ko"], [id$="-en"], [id$="-ja"]').forEach(block => {
        if (block.id) {
            if (block.id.endsWith('-' + lang)) {
                block.style.display = 'block';
            } else if (block.id.endsWith('-ko') || block.id.endsWith('-en') || block.id.endsWith('-ja')) {
                block.style.display = 'none';
            }
        }
    });
}

// Attach click handlers and set initial language on DOM load
function initLanguageSwitcher() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const lang = btn.dataset.lang;
            if (lang) setLanguage(lang);
        });
    });
    setLanguage(currentLang);
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLanguageSwitcher);
} else {
    initLanguageSwitcher();
}
